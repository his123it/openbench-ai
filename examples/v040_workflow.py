#!/usr/bin/env python3
"""Example: the complete v0.4.0 workflow with the offline mock provider.

Runs entirely locally and makes no network requests:

1. audit the reasoning dataset (read-only);
2. run model A as a repeat group of 3 (seeded stochastic mock to simulate sampling noise);
3. run model B once;
4. compare the stored runs (paired statistics, no provider calls);
5. analyse model A's run-to-run variability;
6. create blind preference tasks, simulate two annotators, validate and analyse them;
7. audit the stored runs.

Usage:  python examples/v040_workflow.py [OUTPUT_DIR]     (default: results/v040_workflow)

The mock provider never represents a real language model; the numbers only illustrate the
workflow. Simulated annotations are generated by a fixed rule, not by people.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from openbench import (
    AnnotationImporter,
    ComparisonArm,
    ComparisonPolicy,
    DatasetAuditor,
    DatasetLoader,
    EvaluationConfig,
    ExecutionConfig,
    ExperimentAuditor,
    ExperimentManager,
    MockModelProvider,
    PairedComparisonEngine,
    PreferenceAnalyzer,
    PreferenceTaskBuilder,
    ResponseCache,
)
from openbench.preferences import PreferenceSource, load_rubric, write_task_set
from openbench.reporting_v040 import render_analysis, render_audit, render_preferences
from openbench.stats import decompose_variability


def main(argv: list[str]) -> int:
    repo = Path(__file__).resolve().parent.parent
    out = Path(argv[1]) if len(argv) > 1 else repo / "results" / "v040_workflow"
    out.mkdir(parents=True, exist_ok=True)
    dataset_path = repo / "datasets" / "reasoning" / "sample.jsonl"

    audit = DatasetAuditor().audit(dataset_path)
    (out / "dataset_audit.md").write_text(render_audit(audit.to_dict(), "markdown"), encoding="utf-8")
    print(f"1. Dataset audit: {audit.errors} errors, {audit.warnings} warnings, {audit.infos} info")

    dataset = DatasetLoader.load(str(dataset_path))
    manager = ExperimentManager(out / "experiments")
    cache = ResponseCache(out / "cache")
    config = EvaluationConfig(metric_names=["exact_match", "keyword_coverage", "f1"])
    model_a = MockModelProvider(model_name="example-model-a", stochastic_error_rate=0.25, stochastic_seed=1)
    group = manager.execute_repeated(dataset, model_a, 3, generation_base_seed=100, evaluation_config=config,
                                     execution_config=ExecutionConfig(use_cache=True), cache=cache)
    print(f"2. Repeat group {group.repeat_group_id}: {group.completed_repetitions}/{group.planned_repetitions} completed")

    run_b, _, _ = manager.execute_and_record(dataset, MockModelProvider(model_name="example-model-b"),
                                             evaluation_config=config, execution_config=ExecutionConfig(use_cache=False))
    print(f"3. Single run {run_b.run_id}")

    arms = [ComparisonArm.from_experiments(manager, group.repeat_group_id), ComparisonArm.from_experiments(manager, run_b.run_id)]
    comparison = PairedComparisonEngine().compare(arms, ["exact_match", "f1"], ComparisonPolicy(baseline=run_b.run_id, analysis_seed=0)).to_dict()
    (out / "comparison.md").write_text(render_analysis(comparison, "markdown"), encoding="utf-8")
    (out / "comparison.json").write_text(render_analysis(comparison, "json"), encoding="utf-8")
    for comp in comparison["comparisons"]:
        print(f"4. {comp['metric']['name']}: difference {comp['point_estimate']:+.3f} (n={comp['sample_count']}); {comp['interpretation']}")

    variability = decompose_variability(group.evaluations, ["exact_match"], arm_label=group.repeat_group_id)
    (out / "variability.md").write_text(render_analysis(variability, "markdown"), encoding="utf-8")
    gen = variability["metrics"]["exact_match"]["generation_variability"]
    print(f"5. Items whose exact_match changed across repetitions: {gen['items_with_any_change_rate']:.2f}")

    rubric, instructions = load_rubric(repo / "examples" / "rubric.json")
    sources = [PreferenceSource.from_evaluation(group.records[0].run_id, group.evaluations[0]),
               PreferenceSource.from_evaluation(run_b.run_id, manager.load_evaluation(run_b.run_id))]
    task_set = PreferenceTaskBuilder(7, rubric, instructions).build(*sources)
    written = write_task_set(task_set, out / "preference_tasks", out / "private" / "tasks.key.json", overwrite=True)
    key = json.loads(Path(written["key"]).read_text(encoding="utf-8"))
    lines = []
    for i, task in enumerate(key["tasks"]):  # simulated annotators (a fixed rule, not real judgements)
        for annotator in ("rater_01", "rater_02"):
            outcome = "tie" if (i + len(annotator)) % 4 == 0 else ("response_1" if i % 2 else "response_2")
            lines.append(json.dumps({"annotation_id": f"{annotator}-{i:03d}", "task_id": task["task_id"],
                                     "annotator_id": annotator, "outcome": outcome,
                                     "rubric_scores": {"correctness": 4, "clarity": 3}}))
    (out / "annotations.jsonl").write_text("\n".join(lines) + "\n", encoding="utf-8")
    report = AnnotationImporter(key).load([out / "annotations.jsonl"])
    assert report.valid, report.errors
    prefs = PreferenceAnalyzer([key], analysis_seed=0).analyze(report.annotations, elo=True)
    (out / "preferences.md").write_text(render_preferences(prefs, "markdown"), encoding="utf-8")
    print(f"6. Preference win rate (A, task-weighted): {prefs['pairs'][0]['overall']['win_rate_a_task_weighted']:.3f}")

    group_audit = ExperimentAuditor(manager).audit_group(group.repeat_group_id)
    print(f"7. Group audit: {group_audit.errors} errors, {group_audit.warnings} warnings, {group_audit.infos} info")
    print(f"Reports written to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
