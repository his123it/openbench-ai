@dataclass
class _RawRecord:
    file: str
    line: int
    payload: dict[str, Any]
    record_id: str
    parent_dir: str | None

    def canonical(self) -> dict[str, Any]:
        p = self.payload
        meta = p.get("metadata") if isinstance(p.get("metadata"), dict) else {}
        category = p.get("category")
        return {
            "id": self.record_id,
            "category": category.strip() if isinstance(category, str) else category,
            "prompt": p.get("prompt"),
            "expected_answer": p.get("expected_answer"),
            "metadata": dict(meta),
        }


class DatasetAuditor:
    """Audit JSONL dataset files or a directory of them (read-only)."""

    def __init__(
        self,
        near_duplicate_threshold: float = DEFAULT_NEAR_DUPLICATE_THRESHOLD,
        max_records_for_pairwise: int = MAX_RECORDS_FOR_PAIRWISE,
        metrics: Sequence[str] | None = None,
        metric_options: dict[str, dict[str, Any]] | None = None,
        use_review_notes: bool = True,
        review_notes: list[dict[str, Any]] | None = None,
    ) -> None:
        if not (isinstance(near_duplicate_threshold, (int, float)) and 0.0 < near_duplicate_threshold <= 1.0):
            raise ValueError("near_duplicate_threshold must lie in (0, 1]")
        self.threshold = float(near_duplicate_threshold)
        self.max_pairwise = int(max_records_for_pairwise)
        self.metrics = list(metrics) if metrics else []
        self.metric_options = dict(metric_options or {})
        self.use_review_notes = use_review_notes
        self.review_notes = review_notes if review_notes is not None else (load_review_notes() if use_review_notes else [])

    # -- parsing ------------------------------------------------------------

    def _files(self, target: Path) -> tuple[list[Path], bool]:
        if target.is_dir():
            files = sorted(target.rglob("*.jsonl"))
            return files, True
        return [target], False

    def _parse(self, target: Path) -> tuple[list[_RawRecord], list[AuditFinding], dict[str, Any]]:
        files, is_dir = self._files(target)
        records: list[_RawRecord] = []
        findings: list[AuditFinding] = []
        file_info = []
        for path in files:
            if path.stat().st_size > MAX_FILE_BYTES:
                findings.append(AuditFinding("DQ012", "error", f"{path.name} exceeds the {MAX_FILE_BYTES}-byte audit limit and was not parsed.", details={"file": str(path)}, remediation="Split the file."))
                continue
            raw_bytes = path.read_bytes()
            file_info.append({"path": str(path), "sha256": __import__("hashlib").sha256(raw_bytes).hexdigest()})
            try:
                text = raw_bytes.decode("utf-8")
            except UnicodeDecodeError as exc:
                findings.append(AuditFinding("DQ012", "error", f"{path.name} is not valid UTF-8: {exc.reason}.", details={"file": str(path)}, remediation="Re-encode the file as UTF-8."))
                continue
            parent = path.parent.name if is_dir and path.parent != target else None
            for line_no, line in enumerate(text.splitlines(), start=1):
                if not line.strip():
                    continue
                try:
                    payload = json.loads(line)
                except json.JSONDecodeError as exc:
                    findings.append(AuditFinding("DQ012", "error", f"{path.name}:{line_no}: invalid JSON ({exc.msg}).", details={"file": str(path), "line": line_no}, remediation="Fix the JSON syntax on this line."))
                    continue
                if not isinstance(payload, dict):
                    findings.append(AuditFinding("DQ012", "error", f"{path.name}:{line_no}: expected a JSON object.", details={"file": str(path), "line": line_no}, remediation="Each line must be one JSON object."))
                    continue
                rid = payload.get("id")
                if not isinstance(rid, str) or not rid.strip():
                    findings.append(AuditFinding("DQ012", "error", f"{path.name}:{line_no}: missing or non-string 'id'.", details={"file": str(path), "line": line_no}, remediation="Give every record a unique non-empty string ID."))
                    continue
                meta = payload.get("metadata")
                if meta is not None and not isinstance(meta, dict):
                    findings.append(AuditFinding("DQ012", "error", f"{path.name}:{line_no}: 'metadata' must be an object.", record_ids=(rid.strip(),), details={"file": str(path), "line": line_no}, remediation="Make metadata a JSON object."))
                records.append(_RawRecord(str(path), line_no, payload, rid.strip(), parent))
        return records, findings, {"files": file_info}

    # -- checks -------------------------------------------------------------

    def audit(self, path: str | Path) -> AuditReport:
        target = Path(path)
        if not target.exists():
            raise FileNotFoundError(f"Dataset path does not exist: {target}")
        records, findings, info = self._parse(target)
        findings += self._check_ids(records)
        findings += self._check_prompts_and_references(records)
        dup_findings, near_summary = self._check_duplicates(records)
        findings += dup_findings
        findings += self._check_keywords(records)
        findings += self._check_metric_config(records)
        findings += self._check_versions_and_labels(records)
        findings += self._check_size(records)
        findings = self._apply_notes(records, findings)
        report = AuditReport(
            kind="dataset_audit",
            subject={
                "name": target.stem if target.is_file() else target.name,
                "path": str(target),
                "record_count": len(records),
                "files": info["files"],
                "version_labels": sorted({str(r.payload["metadata"]["version"]) for r in records if isinstance(r.payload.get("metadata"), dict) and r.payload["metadata"].get("version") is not None}),
            },
            parameters={
                "normalisation": "Unicode NFKC, casefold, collapse whitespace, trim (punctuation and accents kept)",
                "shingle_size": SHINGLE_SIZE,
                "near_duplicate_threshold": self.threshold,
                "near_duplicate_method": "character 5-gram Jaccard similarity (lexical heuristic, not semantic)",
                "max_records_for_pairwise": self.max_pairwise,
                "keyword_rule": "each metadata.keywords entry must be a substring of normalize_text(expected_answer) after normalize_text (keyword_coverage semantics)",
                "review_notes_applied": self.use_review_notes,
                "metrics_checked": list(self.metrics),
            },
            findings=_sort_findings(findings),
            extra_summary=near_summary,
        )
        return report

    def _check_ids(self, records: list[_RawRecord]) -> list[AuditFinding]:
        locations: dict[str, list[str]] = {}
        for r in records:
            locations.setdefault(r.record_id, []).append(f"{Path(r.file).name}:{r.line}")
        return [
            AuditFinding("DQ001", "error", f"Record ID '{rid}' appears {len(locs)} times.", record_ids=(rid,), details={"locations": locs}, remediation="Give each record a unique ID; IDs are used to align results.")
            for rid, locs in sorted(locations.items())
            if len(locs) > 1
        ]

    def _check_prompts_and_references(self, records: list[_RawRecord]) -> list[AuditFinding]:
        out = []
        for r in records:
            p = r.payload
            prompt = p.get("prompt")
            if not isinstance(prompt, str) or not prompt.strip():
                out.append(AuditFinding("DQ004", "error", f"Record '{r.record_id}' has a missing, non-string or empty prompt.", record_ids=(r.record_id,), remediation="Provide the prompt text."))
            ref = p.get("expected_answer")
            if "expected_answer" not in p or not isinstance(ref, str):
                out.append(AuditFinding("DQ005", "error", f"Record '{r.record_id}' has a missing or non-string expected_answer.", record_ids=(r.record_id,), remediation="Provide the reference answer as a string."))
            elif not ref.strip() or normalise_prompt(ref) in PLACEHOLDER_REFERENCES:
                out.append(AuditFinding("DQ006", "warning", f"Record '{r.record_id}' has an empty or placeholder reference answer.", record_ids=(r.record_id,), details={"reference": ref[:40]}, remediation="Replace the placeholder with the real reference answer."))
            category = p.get("category")
            if not isinstance(category, str) or not category.strip():
                out.append(AuditFinding("DQ012", "error", f"Record '{r.record_id}' has a missing or empty category.", record_ids=(r.record_id,), remediation="Set the category."))
        return out

    def _check_duplicates(self, records: list[_RawRecord]) -> tuple[list[AuditFinding], dict[str, Any]]:
        out: list[AuditFinding] = []
        normalised = {}
        for r in records:
            prompt = r.payload.get("prompt")
            if isinstance(prompt, str) and prompt.strip():
                normalised.setdefault(r.record_id, normalise_prompt(prompt))
        groups: dict[str, list[str]] = {}
        for rid, text in normalised.items():
            groups.setdefault(text, []).append(rid)
        exact_pairs = set()
        for ids in groups.values():
            if len(ids) > 1:
                ids = sorted(ids)
                out.append(AuditFinding("DQ002", "warning", f"{len(ids)} records have the same prompt after normalisation.", record_ids=tuple(ids), remediation="Check whether the duplicates are intentional; duplicated items are counted more than once in averages."))
                for i in range(len(ids)):
                    for j in range(i + 1, len(ids)):
                        exact_pairs.add((ids[i], ids[j]))
        short = sorted(rid for rid, text in normalised.items() if len(text) < SHINGLE_SIZE)
        long_ = sorted(rid for rid, text in normalised.items() if len(text) > MAX_PROMPT_CHARS_FOR_SHINGLES)
        summary = {"short_prompts_not_compared": len(short), "long_prompts_not_compared": len(long_), "max_near_duplicate_similarity": None, "max_similarity_pair": None}
        if len(normalised) > self.max_pairwise:
            out.append(AuditFinding("DQ014", "info", f"Near-duplicate check skipped: {len(normalised)} records exceed the pairwise limit of {self.max_pairwise}.", details={"reason": "record_limit"}, remediation="Audit smaller subsets or raise the limit."))
            summary["near_duplicate_check"] = "skipped"
            return out, summary
        if long_:
            out.append(AuditFinding("DQ014", "info", f"{len(long_)} prompt(s) longer than {MAX_PROMPT_CHARS_FOR_SHINGLES} characters were not compared for near-duplicates.", record_ids=tuple(long_), details={"reason": "long_prompts"}, remediation="Review long prompts manually."))
        sets = {rid: shingles(text) for rid, text in sorted(normalised.items()) if SHINGLE_SIZE <= len(text) <= MAX_PROMPT_CHARS_FOR_SHINGLES}
        pairs = self._similar_pairs(sets)
        best = None
        for (a, b), sim in sorted(pairs.items()):
            if best is None or sim > best[1] or (sim == best[1] and (a, b) < best[0]):
                best = ((a, b), sim)
            if sim >= self.threshold and (a, b) not in exact_pairs:
                out.append(AuditFinding("DQ003", "warning", f"Possible near-duplicate (heuristic); review manually: '{a}' and '{b}' have character 5-gram Jaccard similarity {sim:.3f}.", record_ids=(a, b), details={"similarity": round(sim, 6), "threshold": self.threshold}, remediation="Review manually; a high lexical similarity is not proof of duplication."))
        if best is not None:
            summary["max_near_duplicate_similarity"] = round(best[1], 6)
            summary["max_similarity_pair"] = list(best[0])
        summary["near_duplicate_check"] = "completed"
        return out, summary

    def _similar_pairs(self, sets: dict[str, frozenset[str]]) -> dict[tuple[str, str], float]:
        """All pairs with Jaccard >= a low reporting floor, via exact prefix filtering.

        To also report the maximum similarity, candidate generation uses a floor of
        min(threshold, 0.3); pairs below the floor are never needed for findings.
        """
        floor = min(self.threshold, 0.3)
        freq = Counter(tok for s in sets.values() for tok in s)
        ordered = {rid: sorted(s, key=lambda t: (freq[t], t)) for rid, s in sets.items()}
        index: dict[str, list[str]] = {}
        candidates: set[tuple[str, str]] = set()
        for rid in sorted(ordered):
            toks = ordered[rid]
            n = len(toks)
            prefix = n - math.ceil(floor * n - 1e-9) + 1
            for tok in toks[: max(prefix, 0)]:
                for other in index.get(tok, ()):
                    candidates.add((other, rid) if other < rid else (rid, other))
                index.setdefault(tok, []).append(rid)
        out = {}
        for a, b in candidates:
            sa, sb = sets[a], sets[b]
            if min(len(sa), len(sb)) < floor * max(len(sa), len(sb)):
                continue
            sim = jaccard(sa, sb)
            if sim >= floor:
                out[(a, b)] = sim
        return out

    def _check_keywords(self, records: list[_RawRecord]) -> list[AuditFinding]:
        out = []
        for r in records:
            meta = r.payload.get("metadata")
            ref = r.payload.get("expected_answer")
            if not isinstance(meta, dict) or not isinstance(ref, str):
                continue
            keywords = meta.get("keywords")
            if keywords is None:
                continue
            if not isinstance(keywords, list) or not all(isinstance(k, str) for k in keywords):
                out.append(AuditFinding("DQ012", "error", f"Record '{r.record_id}' has a metadata.keywords value that is not a list of strings.", record_ids=(r.record_id,), remediation="Use a list of strings."))
                continue
            norm_ref = _legacy_normalize(ref)
            missing = [k for k in keywords if k.strip() and _legacy_normalize(k) not in norm_ref]
            if missing:
                out.append(AuditFinding("DQ007", "warning", f"Record '{r.record_id}': {len(missing)} keyword(s) do not appear in the reference answer, so the reference itself does not score 1.0 on keyword_coverage.", record_ids=(r.record_id,), details={"missing_keywords": missing}, remediation="Check whether the keywords are required; keyword lists cannot express alternatives."))
        return out

    def _check_metric_config(self, records: list[_RawRecord]) -> list[AuditFinding]:
        from openbench.metrics import METRIC_REGISTRY, create_metric

        out = []
        for name in self.metrics:
            key = name.strip().lower()
            if key not in METRIC_REGISTRY:
                out.append(AuditFinding("DQ008", "error", f"Unknown metric '{name}'.", details={"metric": name, "available": sorted({c.name for c in METRIC_REGISTRY.values()})}, remediation="Use a registered metric name."))
                continue
            try:
                create_metric(key, **self.metric_options.get(name, {}))
            except Exception as exc:  # noqa: BLE001 - any construction failure is a config error
                out.append(AuditFinding("DQ008", "error", f"Invalid options for metric '{name}': {type(exc).__name__}.", details={"metric": name, "error": str(exc)[:200]}, remediation="Fix the metric options."))
        for opt_name in sorted(set(self.metric_options) - set(self.metrics)):
            out.append(AuditFinding("DQ008", "error", f"Options given for metric '{opt_name}', which is not requested.", details={"metric": opt_name}, remediation="Remove the options or request the metric."))
        for r in records:
            meta = r.payload.get("metadata")
            if isinstance(meta, dict) and "expected_schema" in meta and meta["expected_schema"] is not None and not isinstance(meta["expected_schema"], dict):
                out.append(AuditFinding("DQ008", "error", f"Record '{r.record_id}' has an expected_schema that is not a JSON object.", record_ids=(r.record_id,), remediation="Use a JSON Schema object."))
        return out

    def _check_versions_and_labels(self, records: list[_RawRecord]) -> list[AuditFinding]:
        out = []
        by_file: dict[str, list[_RawRecord]] = {}
        for r in records:
            by_file.setdefault(r.file, []).append(r)
        for file, recs in sorted(by_file.items()):
            versions = {}
            unversioned = []
            for r in recs:
                meta = r.payload.get("metadata") if isinstance(r.payload.get("metadata"), dict) else {}
                v = meta.get("version")
                if v is None:
                    unversioned.append(r.record_id)
                else:
                    versions.setdefault(str(v), []).append(r.record_id)
            name = Path(file).name if Path(file).parent.name in ("", ".") else f"{Path(file).parent.name}/{Path(file).name}"
            if len(versions) > 1:
                out.append(AuditFinding("DQ009a", "warning", f"{name} contains {len(versions)} distinct version labels.", record_ids=tuple(sorted(i for ids in versions.values() for i in ids)), details={"file": file, "versions": {k: len(v) for k, v in sorted(versions.items())}}, remediation="Check that mixing versions in one file is intended."))
            if versions and unversioned:
                out.append(AuditFinding("DQ009b", "info", f"{name} mixes {len(unversioned)} record(s) without metadata.version and {sum(len(v) for v in versions.values())} with one.", record_ids=tuple(sorted(unversioned)), details={"file": file, "unversioned_count": len(unversioned)}, remediation="Informational; unversioned records are treated as version 0.1.0 by the loader."))
        for r in records:
            meta = r.payload.get("metadata") if isinstance(r.payload.get("metadata"), dict) else {}
            diff = meta.get("difficulty")
            if diff is not None and diff not in ALLOWED_DIFFICULTIES:
                out.append(AuditFinding("DQ009c", "warning", f"Record '{r.record_id}' has difficulty {diff!r}, not easy/medium/hard.", record_ids=(r.record_id,), remediation="Use easy, medium or hard."))
            category = r.payload.get("category")
            if r.parent_dir is not None and isinstance(category, str) and category.strip() and category.strip() != r.parent_dir:
                out.append(AuditFinding("DQ009d", "warning", f"Record '{r.record_id}' has category '{category}' in directory '{r.parent_dir}'.", record_ids=(r.record_id,), remediation="Move the record or correct its category."))
        return out

    def _check_size(self, records: list[_RawRecord]) -> list[AuditFinding]:
        n = len({r.record_id for r in records})
        if n == 0:
            return [AuditFinding("DQ013", "error", "No records were found.", remediation="Check the path.")]
        if n < SMALL_DATASET_WARNING_BELOW:
            return [AuditFinding("DQ013", "warning", f"Only {n} record(s): too few for any statistical conclusion (fewer than {SMALL_DATASET_WARNING_BELOW}).", details={"records": n}, remediation="Add records before comparing models statistically.")]
        if n < SMALL_DATASET_INFO_BELOW:
            return [AuditFinding("DQ013", "info", f"Only {n} records: comparisons will have low power and wide intervals (fewer than {SMALL_DATASET_INFO_BELOW}).", details={"records": n}, remediation="Interpret statistical results with care or use more records.")]
        return []

    def _apply_notes(self, records: list[_RawRecord], findings: list[AuditFinding]) -> list[AuditFinding]:
        if not self.use_review_notes or not self.review_notes:
            return findings
        hashes = {}
        for r in records:
            hashes.setdefault(r.record_id, canonical_record_sha256(r.canonical()))
        out = []
        for f in findings:
            if f.check_id == "DQ007" and len(f.record_ids) == 1:
                rid = f.record_ids[0]
                note = next((n for n in self.review_notes if n["check_id"] == "DQ007" and n["record_id"] == rid and n["content_sha256"] == hashes.get(rid)), None)
                if note is not None:
                    f = AuditFinding(f.check_id, f.severity, f.message, f.record_ids, f.run_ids, f.remediation, f.details, note.get("classification"), note.get("explanation"))
            out.append(f)
        for note in self.review_notes:
            if note["check_id"] not in ("DQ010", "DQ011"):
                continue
            rid = note["record_id"]
            if hashes.get(rid) != note["content_sha256"]:
                continue
            severity = "info" if note["check_id"] == "DQ010" else "warning"
            out.append(AuditFinding(note["check_id"], severity, note.get("message", CHECK_TITLES[note["check_id"]]), record_ids=(rid,), remediation=note.get("remediation", ""), details={"source": "review_notes"}, classification=note.get("classification"), classification_note=note.get("explanation")))
        return out


