def normalise_prompt(text: str) -> str:
    """NFKC, then casefold, then collapse whitespace runs to one space, then trim."""
    return " ".join(unicodedata.normalize("NFKC", text).casefold().split())


def _legacy_normalize(text: str) -> str:
    from openbench.metrics.normalization import normalize_text

    return normalize_text(text)


def shingles(text: str, size: int = SHINGLE_SIZE) -> frozenset[str]:
    if len(text) < size:
        return frozenset()
    return frozenset(text[i : i + size] for i in range(len(text) - size + 1))


def jaccard(a: frozenset[str], b: frozenset[str]) -> float:
    if not a and not b:
        return 1.0
    return len(a & b) / len(a | b)


@dataclass(frozen=True)
class AuditFinding:
    check_id: str
    severity: str
    message: str
    record_ids: tuple[str, ...] = ()
    run_ids: tuple[str, ...] = ()
    remediation: str = ""
    details: dict[str, Any] = field(default_factory=dict)
    classification: str | None = None
    classification_note: str | None = None

    def __post_init__(self) -> None:
        if self.severity not in SEVERITIES:
            raise ValueError(f"severity must be one of {SEVERITIES}")

    @property
    def title(self) -> str:
        return CHECK_TITLES.get(self.check_id, self.check_id)

    def to_dict(self) -> dict[str, Any]:
        return {
            "check_id": self.check_id,
            "severity": self.severity,
            "title": self.title,
            "message": self.message,
            "record_ids": list(self.record_ids),
            "run_ids": list(self.run_ids),
            "remediation": self.remediation,
            "details": dict(self.details),
            "classification": self.classification,
            "classification_note": self.classification_note,
        }


@dataclass
class AuditReport:
    kind: str
    subject: dict[str, Any]
    parameters: dict[str, Any]
    findings: list[AuditFinding]
    extra_summary: dict[str, Any] = field(default_factory=dict)

    @property
    def errors(self) -> int:
        return sum(1 for f in self.findings if f.severity == "error")

    @property
    def warnings(self) -> int:
        return sum(1 for f in self.findings if f.severity == "warning")

    @property
    def infos(self) -> int:
        return sum(1 for f in self.findings if f.severity == "info")

    @property
    def exit_code(self) -> int:
        """1 only when an error-severity finding exists (D18)."""
        return 1 if self.errors else 0

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema_version": AUDIT_SCHEMA_VERSION,
            "audit_version": AUDIT_VERSION,
            "kind": self.kind,
            "audited_at": datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
            "subject": dict(self.subject),
            "parameters": dict(self.parameters),
            "findings": [f.to_dict() for f in self.findings],
            "summary": {
                "errors": self.errors,
                "warnings": self.warnings,
                "info": self.infos,
                "by_check": dict(sorted(Counter(f.check_id for f in self.findings).items())),
                **self.extra_summary,
            },
            "non_mutation": "Audits are read-only; no dataset, run or score was modified.",
        }


def _sort_findings(findings: list[AuditFinding]) -> list[AuditFinding]:
    order = {s: i for i, s in enumerate(SEVERITIES)}
    return sorted(findings, key=lambda f: (order[f.severity], f.check_id, f.record_ids, f.run_ids, f.message))


