class ExperimentAuditor:
    """Read-only quality checks for stored runs and repeat groups (EQ checks)."""

    def __init__(self, manager: Any) -> None:
        self.manager = manager

    def audit_run(self, run_id: str) -> AuditReport:
        findings = self._run_findings(run_id)
        return AuditReport("experiment_audit", {"run_id": run_id}, {"insufficient_data_thresholds": {"warning_below": 10, "info_below": 30}}, _sort_findings(findings))

    def audit_group(self, repeat_group_id: str) -> AuditReport:
        findings: list[AuditFinding] = []
        check = self.manager.verify_group(repeat_group_id)
        for problem in check["problems"]:
            if "integrity" in problem:
                continue
            findings.append(AuditFinding("EQ010", "error", problem, run_ids=(repeat_group_id,), remediation="Inspect the member runs' lineage before analysing the group."))
        planned = int(check.get("planned_repetitions") or 0)
        members = self.manager.list_runs(repeat_group_id=repeat_group_id)
        completed = sum(1 for m in members if m.status == "completed")
        if completed < planned:
            findings.append(AuditFinding("EQ004", "warning", f"{completed} of {planned} planned repetitions completed.", run_ids=(repeat_group_id,), details={"planned": planned, "completed": completed, "members": len(members)}, remediation=f"Run 'openbench runs resume {repeat_group_id}'."))
        for m in sorted(members, key=lambda r: (r.repetition_index, r.run_id)):
            findings += self._run_findings(m.run_id)
        return AuditReport("experiment_audit", {"repeat_group_id": repeat_group_id, "member_run_ids": sorted(m.run_id for m in members)}, {"insufficient_data_thresholds": {"warning_below": 10, "info_below": 30}}, _sort_findings(findings))

    def _run_findings(self, run_id: str) -> list[AuditFinding]:
        from openbench.exceptions import OpenBenchError

        findings: list[AuditFinding] = []
        rid = (run_id,)
        try:
            rec = self.manager.load_run_record(run_id)
        except (KeyError, OpenBenchError) as exc:
            return [AuditFinding("EQ011", "error", f"Run configuration could not be read: {exc}", run_ids=rid, remediation="Restore config.json from a backup; do not hand-edit run artifacts.")]
        check = self.manager.verify_run(run_id)
        if not check.valid:
            findings.append(AuditFinding("EQ003", "error", "Integrity verification failed.", run_ids=rid, details={"missing_artifacts": check.missing_artifacts, "changed_artifacts": check.changed_artifacts, "inconsistent_metadata": check.inconsistent_metadata}, remediation="Treat results from this run as untrusted until the cause is understood."))
        if rec.status in ("partial", "failed"):
            findings.append(AuditFinding("EQ002", "warning", f"Run status is '{rec.status}'.", run_ids=rid, details={"failed_items": rec.failed_items, "total_items": rec.total_items}, remediation=f"Run 'openbench runs resume {rec.run_id}' if it was provider-executed."))
        if not rec.lineage or rec.lineage.get("legacy_run"):
            findings.append(AuditFinding("EQ009", "info", "Run was created before v0.4.0 and has no lineage (single run, seed status unknown).", run_ids=rid, remediation="Informational; compatibility checks fall back to the dataset checksum."))
        if rec.execution_origin != "provider_executed":
            findings.append(AuditFinding("EQ012", "info", f"Responses were not generated by the execution engine (origin '{rec.execution_origin}').", run_ids=rid))
        try:
            ev = self.manager.load_evaluation(run_id)
        except (KeyError, OpenBenchError) as exc:
            findings.append(AuditFinding("EQ011", "error", f"evaluation.json could not be read: {exc}", run_ids=rid))
            return findings
        if ev.missing_response_ids:
            findings.append(AuditFinding("EQ001", "warning", f"{len(ev.missing_response_ids)} item(s) have no model output.", record_ids=tuple(sorted(ev.missing_response_ids)), run_ids=rid, remediation="Missing outputs are 0.0 in headline scores; analyses use an explicit missing-data policy."))
        if ev.unknown_response_ids:
            findings.append(AuditFinding("EQ007", "warning", f"{len(ev.unknown_response_ids)} response ID(s) do not match any dataset record.", record_ids=tuple(sorted(ev.unknown_response_ids)), run_ids=rid, remediation="Check that the responses belong to this dataset."))
        bad = []
        for item in ev.individual_results:
            for name, mr in item.metrics.items():
                if not math.isfinite(mr.score) or not 0.0 <= mr.score <= 1.0:
                    bad.append(f"{item.id}:{name}")
        if bad:
            findings.append(AuditFinding("EQ008", "error", f"{len(bad)} metric result(s) are non-finite or outside [0, 1].", record_ids=tuple(sorted({b.split(':')[0] for b in bad})), run_ids=rid, details={"results": bad[:50]}, remediation="Do not analyse these results until the metric is fixed."))
        responses_path = Path(rec.run_dir) / "responses.json"
        if responses_path.exists():
            try:
                payload = json.loads(responses_path.read_text(encoding="utf-8"))
                ids = [r.get("id") for r in payload.get("responses", []) if isinstance(r, dict)]
                dups = sorted(i for i, c in Counter(ids).items() if c > 1)
                if dups:
                    findings.append(AuditFinding("EQ006", "error", f"{len(dups)} record ID(s) appear more than once in responses.json.", record_ids=tuple(dups), run_ids=rid))
            except (json.JSONDecodeError, AttributeError):
                findings.append(AuditFinding("EQ011", "error", "responses.json is not a valid response payload.", run_ids=rid))
        n = ev.evaluated_items_count
        if n < SMALL_DATASET_WARNING_BELOW:
            findings.append(AuditFinding("EQ005", "warning", f"Only {n} evaluated item(s): too few for statistical analysis.", run_ids=rid, details={"evaluated_items": n}))
        elif n < SMALL_DATASET_INFO_BELOW:
            findings.append(AuditFinding("EQ005", "info", f"Only {n} evaluated items: statistical comparisons will have low power.", run_ids=rid, details={"evaluated_items": n}))
        return findings
