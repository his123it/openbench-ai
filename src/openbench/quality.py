def load_review_notes(path: str | Path | None = None) -> list[dict[str, Any]]:
    """Load reviewed notes (packaged ``quality_notes.json`` by default)."""
    if path is None:
        text = resources.files("openbench").joinpath("quality_notes.json").read_text(encoding="utf-8")
    else:
        text = Path(path).read_text(encoding="utf-8")
    data = json.loads(text)
    notes = data.get("notes") if isinstance(data, dict) else None
    if not isinstance(notes, list):
        raise ValueError("review notes must be an object with a 'notes' list")
    for note in notes:
        if not isinstance(note, dict) or not {"record_id", "content_sha256", "check_id"} <= set(note):
            raise ValueError("each review note needs record_id, content_sha256 and check_id")
        if note["check_id"] not in {"DQ007", "DQ010", "DQ011"}:
            raise ValueError("review notes may only classify DQ007 or emit DQ010/DQ011")
    return notes


