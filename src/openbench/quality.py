DEFAULT_NEAR_DUPLICATE_THRESHOLD = 0.85
MAX_RECORDS_FOR_PAIRWISE = 5_000
MAX_PROMPT_CHARS_FOR_SHINGLES = 20_000
PLACEHOLDER_REFERENCES = {"todo", "tbd", "n/a", "na", "...", "none", "null", "xxx", "?"}
ALLOWED_DIFFICULTIES = {"easy", "medium", "hard"}
