"""Non-mutating dataset and experiment quality audits (plan section 7; v0.4.0).

Auditors only read files. They never rewrite, delete, reorder or "fix" records, never
change scores, and never hide findings. Review notes (``quality_notes.json``) can attach
a classification to a heuristic finding or add a DQ010/DQ011 finding for an issue that
cannot be detected automatically; they are keyed by record ID **and** record content
SHA-256, so a note never applies to edited content or to a same-ID record elsewhere.

Dataset checks (DQ) parse raw JSONL themselves, so they can report records that the
dataset loader would reject. Experiment checks (EQ) read stored run directories and
repeat-group lineage.

The near-duplicate check (DQ003) is a lexical heuristic: character 5-gram Jaccard
similarity after Unicode NFKC normalisation, case folding and whitespace collapsing.
It is **not** semantic duplicate detection, and a high score is not proof of duplication.
"""

